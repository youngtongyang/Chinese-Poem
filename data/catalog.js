window.CATALOG.placeById = function (id) {
  return this.places.find(function (p) { return p.id === id; }) || null;
};
window.CATALOG.poemById = function (id) {
  return this.poems.find(function (p) { return p.id === id; }) || null;
};
window.CATALOG.authorById = function (id) {
  return this.authors.find(function (a) { return a.id === id; }) || null;
};
window.CATALOG.poemsAt = function (placeId) {
  return this.poems.filter(function (p) { return p.placeId === placeId; });
};
window.CATALOG.ZONE_ORDER = ['塞北', '中原', '巴蜀', '长江', '东南'];
window.CATALOG.gradeLabel = function (poem) {
  if (!poem || poem.grade == null) return '课外';
  if (poem.grade === '高中') return '高中';
  var cn = ['', '一', '二', '三', '四', '五', '六', '七', '八', '九'];
  var n = cn[poem.grade];
  if (!n) return '课外';
  return n + '年级' + (poem.volume ? poem.volume + '册' : '');
};
window.CATALOG.gradeLabelShort = function (poem) {
  if (!poem || poem.grade == null) return '课外';
  if (poem.grade === '高中') return '高中';
  var cn = ['', '一', '二', '三', '四', '五', '六', '七', '八', '九'];
  var n = cn[poem.grade];
  if (!n) return '课外';
  return n + (poem.volume || '');
};
