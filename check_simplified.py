# 注意：凝/固/谷/身/赤/赴/京/推/崇/骨/奏/破/河/詩→诗 等两体同形，不入表


def visible_text(html: str) -> str:
    """剥掉 style/script/注释/标签，只留浏览器会渲染的文字。"""
    t = re.sub(r'<style[\s\S]*?</style>', '', html)
    t = re.sub(r'<script[\s\S]*?</script>', '', t)
    t = re.sub(r'<!--[\s\S]*?-->', '', t)
    t = re.sub(r'<[^>]+>', '', t)
    return t


def main() -> int:
    path = sys.argv[1] if len(sys.argv) > 1 else 'index.html'
    html = open(path, encoding='utf-8').read()

    # 1) 可见文本必须零繁体（硬要求）
    text = visible_text(html)
    hits = {}
    for i, ch in enumerate(text):
        if ch in TRAD:
            hits.setdefault(ch, []).append(text[max(0, i - 15):i + 15].replace('\n', ' '))

    # 2) lang 属性检查
    lang_ok = 'lang="zh-CN"' in html

    # 3) 字体栈检查
    font_ok = "'SimSun'" in html

    print(f"文件: {path}")
    print(f"可见文本字符数: {len(text)}")
    print(f"lang=zh-CN: {lang_ok}")
    print(f"字体栈含 SimSun: {font_ok}")

    if hits:
        print(f"\n✗ 发现 {len(hits)} 种繁体字:")
        for ch, ctxs in sorted(hits.items()):
            print(f"  [{ch}] 应为 [{TRAD[ch]}]  例: …{ctxs[0]}…")
        return 1

    print("\n✓ 可见文本零繁体 —— 全部简体")
    return 0 if (lang_ok and font_ok) else 1


if __name__ == '__main__':
    sys.exit(main())
